"""The game's own typeface (gpu/vk/vk_startup_paint.h, the start-up screen) from assets/fonts: a C header with the TrueType
files' bytes, written by nx2/build.py into the build's own folder. The game hands them to Windows for its own process alone
(AddFontMemResourceEx): nothing is installed, and a PC without them shows the same screen in its usual face.

    python nx2/fonts_embed.py [out.h]

Rubik (SIL Open Font License 1.1, assets/fonts/OFL-Rubik.txt): Regular and Bold under the family "Rubik", Medium and ExtraBold
under families of their own ("Rubik Medium", "Rubik ExtraBold"), as the files name them for GDI.
"""
import os
import sys

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
FONTS = os.path.join(ROOT, "assets", "fonts")
FILES = ("Rubik-Regular.ttf", "Rubik-Medium.ttf", "Rubik-Bold.ttf", "Rubik-ExtraBold.ttf")


def header(folder=FONTS):
    present = [f for f in FILES if os.path.isfile(os.path.join(folder, f))]
    if len(present) != len(FILES):   # (a source tree without them: the screen keeps the system's face)
        return "// generated by nx2/fonts_embed.py: no assets/fonts\n#pragma once\n"
    lines = ["// generated by nx2/fonts_embed.py from assets/fonts: do not edit", "#pragma once", "#define RELINK_FONTS 1"]
    names = []
    for i, name in enumerate(FILES):
        data = open(os.path.join(folder, name), "rb").read()
        names.append("relink_font_%d" % i)
        lines.append("static const unsigned char relink_font_%d[%d] = {" % (i, len(data)))
        for at in range(0, len(data), 40):
            lines.append(",".join(str(b) for b in data[at:at + 40]) + ",")
        lines.append("};")
    lines.append("static const unsigned char* const relink_fonts[%d] = {%s};" % (len(FILES), ", ".join(names)))
    lines.append("static const unsigned relink_font_sizes[%d] = {%s};" % (
        len(FILES), ", ".join("sizeof %s" % n for n in names)))
    return "\n".join(lines) + "\n"


def write(out_path, folder=FONTS):
    """Writes the header when it differs (an unchanged one keeps its timestamp); returns its text"""
    text = header(folder)
    try:
        with open(out_path, encoding="utf-8") as f:
            if f.read() == text:
                return text
    except OSError:
        pass
    os.makedirs(os.path.dirname(out_path) or ".", exist_ok=True)
    with open(out_path, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    return text


if __name__ == "__main__":
    write(sys.argv[1] if len(sys.argv) > 1 else "relink_fonts.h")
